        // Filters the user grid by name, email, department, status, or role using the search box text.
        private void SearchUsers()
        {
            string search = userSearchTextBox.Text.Trim().ToLower();

            if (string.IsNullOrWhiteSpace(search))
            {
                LoadUsersGrid();
                SelectFirstUserRowIfAvailable();
                return;
            }

            var filteredUsers = _store.Users
                .Where(user =>
                    user.FirstName.ToLower().Contains(search) ||
                    user.LastName.ToLower().Contains(search) ||
                    user.DisplayName.ToLower().Contains(search) ||
                    user.Email.ToLower().Contains(search) ||
                    user.Department.ToLower().Contains(search) ||
                    user.Status.ToString().ToLower().Contains(search) ||
                    user.Role.ToString().ToLower().Contains(search))
                .ToList();

            usersGridView.DataSource = null;
            usersGridView.DataSource = filteredUsers;

            FormatUsersGrid();
            SelectFirstUserRowIfAvailable();
        }

        // Returns the UserAccount bound to the currently selected user grid row.
        private Models.UserAccount GetSelectedUser()
        {
            if (usersGridView.CurrentRow == null)
                return null;

            return usersGridView.CurrentRow.DataBoundItem as Models.UserAccount;
        }

        // Returns the selected assigned device if one exists; otherwise falls back to the available-device combo box.
        private Models.Device GetSelectedDevice()
        {
            var assignedDevice = GetSelectedAssignedDevice();

            if (assignedDevice != null)
                return assignedDevice;

            return devicesComboBox.SelectedItem as Models.Device;
        }

        // Returns the Device object selected in the selected user's assigned-devices list.
        private Models.Device GetSelectedAssignedDevice()
        {
            return userDevicesListBox.SelectedItem as Models.Device;
        }

        // Finds the specific device named by the current ticket's RequiredDeviceName field.
        private Models.Device GetRequiredTicketDevice()
        {
            if (_currentTicket == null || string.IsNullOrWhiteSpace(_currentTicket.RequiredDeviceName))
                return null;

            return _store.Devices.FirstOrDefault(device =>
                device.DeviceName.Equals(_currentTicket.RequiredDeviceName, StringComparison.OrdinalIgnoreCase));
        }

        // Loads the current ticket title, description, and expected action checklist into the ticket panel.
        private void DisplayTicket(Models.TicketScenario ticket)
        {
            _currentTicket = ticket;

            ticketTitleLabel.Text = ticket.Title;
            ticketDescriptionTextBox.Text = ticket.Description;

            expectedActionsCheckedListBox.Items.Clear();

            foreach (var action in ticket.ExpectedActions)
            {
                expectedActionsCheckedListBox.Items.Add(action, false);
            }
        }

        // Refreshes the selected-user detail panel, mailbox status, group list, assigned devices, and device health view.
        private void DisplaySelectedUser()
        {
            var user = GetSelectedUser();

            userGroupsListBox.Items.Clear();
            userDevicesListBox.Items.Clear();

            if (user == null)
            {
                selectedNameLabel.Text = "-";
                selectedEmailLabel.Text = "-";
                selectedDepartmentLabel.Text = "-";
                selectedStatusLabel.Text = "-";
                selectedRoleLabel.Text = "-";
                mailLicenseLabel.Text = "-";
                mailboxStatusLabel.Text = "-";
                mailboxFullLabel.Text = "-";
                forwardingStatusLabel.Text = "-";
                forwardingAddressLabel.Text = "-";
                return;
            }

            selectedNameLabel.Text = user.DisplayName;
            selectedEmailLabel.Text = user.Email;
            selectedDepartmentLabel.Text = user.Department;
            selectedStatusLabel.Text = user.Status.ToString();
            selectedRoleLabel.Text = user.Role.ToString();

            mailLicenseLabel.Text = user.HasMailLicense ? "Yes" : "No";
            mailboxStatusLabel.Text = user.MailboxStatus;
            mailboxFullLabel.Text = user.MailboxFull ? "Yes" : "No";
            forwardingStatusLabel.Text = user.ForwardingEnabled ? "Enabled" : "Disabled";
            forwardingAddressLabel.Text = string.IsNullOrWhiteSpace(user.ForwardingAddress)
                ? "-"
                : user.ForwardingAddress;

            var userGroups = _store.Groups
                .Where(group => user.GroupIds.Contains(group.Id))
                .ToList();

            foreach (var group in userGroups)
            {
                userGroupsListBox.Items.Add(group.Name);
            }

            if (userGroups.Count == 0)
            {
                userGroupsListBox.Items.Add("No groups assigned");
            }

            var userDevices = _store.Devices
       .Where(device => user.DeviceIds.Contains(device.Id))
       .ToList();

            foreach (var device in userDevices)
            {
                userDevicesListBox.Items.Add(device);
            }

            if (userDevices.Count == 0)
            {
                userDevicesListBox.Items.Add("No devices assigned");
            }

            if (userDevicesListBox.Items.Count > 0 &&
    userDevicesListBox.Items[0] is Models.Device)
            {
                userDevicesListBox.SelectedIndex = 0;
            }
            DisplaySelectedDeviceHealth();
        }

        // Refreshes the Device Health panel from the currently selected assigned or available device.
        private void DisplaySelectedDeviceHealth()
        {
            var device = GetSelectedDevice();

            if (device == null)
            {
                selectedDeviceNameLabel.Text = "-";
                bitLockerStatusLabel.Text = "-";
                windowsUpdateStatusLabel.Text = "-";
                defenderStatusLabel.Text = "-";
                diskSpaceStatusLabel.Text = "-";
                lastCheckInStatusLabel.Text = "-";
                localAdminStatusLabel.Text = "-";
                deviceHealthStatusLabel.Text = "-";
                return;
            }

            selectedDeviceNameLabel.Text = device.DeviceName;
            bitLockerStatusLabel.Text = device.BitLockerEnabled ? "Enabled" : "Disabled";
            windowsUpdateStatusLabel.Text = device.WindowsUpdatePending ? "Pending" : "Current";
            defenderStatusLabel.Text = device.DefenderEnabled ? "Enabled" : "Disabled";
            diskSpaceStatusLabel.Text = $"{device.DiskSpaceFreePercent}% free";
            lastCheckInStatusLabel.Text = $"{device.DaysSinceLastCheckIn} day(s) ago";
            localAdminStatusLabel.Text = device.LocalAdminGranted ? "Granted" : "Not Granted";
            deviceHealthStatusLabel.Text = device.DeviceHealthStatus;
        }

