        // Routes the current ticket to the correct checklist updater based on scenario type.
        private void UpdateTicketProgress()
        {
            if (_currentTicket == null)
                return;

            switch (_currentTicket.ScenarioType)
            {
                case Models.TicketScenarioType.NewHireOnboarding:
                    UpdateNewHireOnboardingChecklist();
                    break;

                case Models.TicketScenarioType.PasswordReset:
                    UpdatePasswordResetChecklist();
                    break;

                case Models.TicketScenarioType.SalesDriveAccess:
                    UpdateSalesDriveAccessChecklist();
                    break;

                case Models.TicketScenarioType.LostLaptop:
                    UpdateLostLaptopChecklist();
                    break;

                case Models.TicketScenarioType.EmployeeOffboarding:
                    UpdateEmployeeOffboardingChecklist();
                    break;

                case Models.TicketScenarioType.ReplacementLaptop:
                    UpdateReplacementLaptopChecklist();
                    break;

                case Models.TicketScenarioType.EmailTroubleshooting:
                    UpdateEmailTroubleshootingChecklist();
                    break;

                case Models.TicketScenarioType.DeviceHealthTroubleshooting:
                    UpdateDeviceHealthTroubleshootingChecklist();
                    break;
            }

            CheckIfTicketReadyToComplete();
        }

        // Auto-checks onboarding checklist items based on whether the new user, group access, role, device, and audit entry exist.
        private void UpdateNewHireOnboardingChecklist()
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email.Equals(_currentTicket.TargetUserEmail, StringComparison.OrdinalIgnoreCase));

            bool userExists = user != null;

            SetChecklistItemChecked(
                $"Create account for {_currentTicket.RequiredFirstName} {_currentTicket.RequiredLastName}",
                userExists
            );

            if (!userExists)
                return;

            var selectedUser = GetSelectedUser();

            SetChecklistItemChecked(
                $"Find and select {user.DisplayName}",
                selectedUser != null && selectedUser.Email.Equals(user.Email, StringComparison.OrdinalIgnoreCase)
            );

            SetChecklistItemChecked(
                $"Confirm {user.FirstName}'s account is Active",
                user.Status == Models.UserStatus.Active
            );

            SetChecklistItemChecked(
                $"Assign {user.FirstName} the {_currentTicket.RequiredRole} role",
                user.Role == _currentTicket.RequiredRole
            );

            var requiredGroup = _store.Groups
                .FirstOrDefault(g => g.Name.Equals(_currentTicket.RequiredGroupName, StringComparison.OrdinalIgnoreCase));

            bool hasRequiredGroup =
                requiredGroup != null &&
                user.GroupIds.Contains(requiredGroup.Id);

            SetChecklistItemChecked(
                $"Add {user.FirstName} to {_currentTicket.RequiredGroupName}",
                hasRequiredGroup
            );

            bool hasActiveAssignedDevice = _store.Devices.Any(d =>
                d.AssignedUserId == user.Id &&
                d.Status == Models.DeviceStatus.Active);

            SetChecklistItemChecked(
                $"Assign an active device to {user.FirstName}",
                hasActiveAssignedDevice
            );

            bool hasCreatedUserAudit = _store.AuditEntries.Any(a =>
                a.Action == "Created User" &&
                a.Target == user.DisplayName);

            SetChecklistItemChecked(
                "Verify user creation appears in the audit log",
                hasCreatedUserAudit
            );
        }

        // Routes ticket completion validation to the correct validator based on scenario type.
        private bool ValidateCurrentTicket(out string message)
        {
            message = "";

            if (_currentTicket == null)
            {
                message = "Load a ticket first.";
                return false;
            }

            switch (_currentTicket.ScenarioType)
            {
                case Models.TicketScenarioType.NewHireOnboarding:
                    return ValidateNewHireOnboardingTicket(out message);

                case Models.TicketScenarioType.SalesDriveAccess:
                    return ValidateSalesDriveAccessTicket(out message);

                case Models.TicketScenarioType.EmployeeOffboarding:
                    return ValidateEmployeeOffboardingTicket(out message);

                case Models.TicketScenarioType.ReplacementLaptop:
                    return ValidateReplacementLaptopTicket(out message);

                case Models.TicketScenarioType.LostLaptop:
                    return ValidateLostLaptopTicket(out message);

                case Models.TicketScenarioType.PasswordReset:
                    return ValidatePasswordResetTicket(out message);

                case Models.TicketScenarioType.EmailTroubleshooting:
                    return ValidateEmailTroubleshootingTicket(out message);

                case Models.TicketScenarioType.DeviceHealthTroubleshooting:
                    return ValidateDeviceHealthTroubleshootingTicket(out message);

                default:
                    message = "Unknown ticket type.";
                    return false;
            }
        }

        // Validates that the target user's password reset was performed and audited.
        private bool ValidatePasswordResetTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email == _currentTicket.TargetUserEmail);

            if (user == null)
            {
                message = "Target user was not found.";
                return false;
            }

            if (user.Status == Models.UserStatus.SoftDeleted)
            {
                message = $"{user.DisplayName} is soft-deleted. Password reset should not be completed for this account.";
                return false;
            }

            bool hasPasswordResetAudit = _store.AuditEntries.Any(a =>
                a.Action == "Reset Password" &&
                a.Target == user.DisplayName);

            if (!hasPasswordResetAudit)
            {
                message = $"No password reset audit entry found for {user.DisplayName}.";
                return false;
            }

            message = "Password reset ticket completed successfully.";
            return true;
        }

        // Validates that the target user is active and has Sales shared-drive access.
        private bool ValidateSalesDriveAccessTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email == _currentTicket.TargetUserEmail);

            if (user == null)
            {
                message = "Target user was not found.";
                return false;
            }

            if (user.Status != Models.UserStatus.Active)
            {
                message = $"{user.DisplayName}'s account is not active.";
                return false;
            }

            var salesGroup = _store.Groups
                .FirstOrDefault(g => g.Name == "Sales-SharedDrive-Access");

            if (salesGroup == null)
            {
                message = "Sales-SharedDrive-Access group was not found.";
                return false;
            }

            if (!user.GroupIds.Contains(salesGroup.Id))
            {
                message = $"{user.DisplayName} is not a member of Sales-SharedDrive-Access.";
                return false;
            }

            message = "Sales drive access ticket completed successfully.";
            return true;
        }

        // Validates lost-laptop remediation: device unassigned/lost, password reset performed, and audit entries exist.
        private bool ValidateLostLaptopTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email == _currentTicket.TargetUserEmail);

            if (user == null)
            {
                message = "Target user was not found.";
                return false;
            }

            bool hasAssignedDevices = _store.Devices.Any(d => d.AssignedUserId == user.Id);

            if (hasAssignedDevices)
            {
                message = $"{user.DisplayName} still has assigned devices.";
                return false;
            }

            bool hasLostDeviceAudit = _store.AuditEntries.Any(a =>
                a.Action == "Marked Device Lost");

            if (!hasLostDeviceAudit)
            {
                message = "No lost device audit entry was found.";
                return false;
            }

            bool hasPasswordResetAudit = _store.AuditEntries.Any(a =>
                a.Action == "Reset Password" &&
                a.Target == user.DisplayName);

            if (!hasPasswordResetAudit)
            {
                message = $"No password reset audit entry found for {user.DisplayName}.";
                return false;
            }

            message = "Lost laptop ticket completed successfully.";
            return true;
        }

        // Validates offboarding: account disabled or soft-deleted, group access removed, and devices unassigned.
        private bool ValidateEmployeeOffboardingTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email == _currentTicket.TargetUserEmail);

            if (user == null)
            {
                message = "Target user was not found.";
                return false;
            }

            if (user.Status != Models.UserStatus.Disabled &&
                user.Status != Models.UserStatus.SoftDeleted)
            {
                message = $"{user.DisplayName}'s account should be disabled or soft-deleted.";
                return false;
            }

            if (user.GroupIds.Count > 0)
            {
                message = $"{user.DisplayName} still has group access assigned.";
                return false;
            }

            bool hasAssignedDevices = _store.Devices.Any(d => d.AssignedUserId == user.Id);

            if (hasAssignedDevices)
            {
                message = $"{user.DisplayName} still has assigned devices.";
                return false;
            }

            message = "Employee offboarding ticket completed successfully.";
            return true;
        }

        // Validates that the target user has an active assigned device.
        private bool ValidateReplacementLaptopTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email == _currentTicket.TargetUserEmail);

            if (user == null)
            {
                message = "Target user was not found.";
                return false;
            }

            if (user.Status != Models.UserStatus.Active)
            {
                message = $"{user.DisplayName}'s account must be active.";
                return false;
            }

            bool hasActiveAssignedDevice = _store.Devices.Any(d =>
                d.AssignedUserId == user.Id &&
                d.Status == Models.DeviceStatus.Active);

            if (!hasActiveAssignedDevice)
            {
                message = $"{user.DisplayName} does not have an active assigned device.";
                return false;
            }

            message = "Replacement laptop ticket completed successfully.";
            return true;
        }

        // Validates new-hire setup: user exists, status, department, role, required group, assigned device, and audit log.
        private bool ValidateNewHireOnboardingTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email.Equals(_currentTicket.TargetUserEmail, StringComparison.OrdinalIgnoreCase));

            if (user == null)
            {
                message = $"User {_currentTicket.RequiredFirstName} {_currentTicket.RequiredLastName} has not been created.";
                return false;
            }

            if (user.Status != Models.UserStatus.Active)
            {
                message = $"{user.DisplayName}'s account must be Active.";
                return false;
            }

            if (!user.Department.Equals(_currentTicket.RequiredDepartment, StringComparison.OrdinalIgnoreCase))
            {
                message = $"{user.DisplayName} must be in the {_currentTicket.RequiredDepartment} department.";
                return false;
            }

            if (user.Role != _currentTicket.RequiredRole)
            {
                message = $"{user.DisplayName} must have the {_currentTicket.RequiredRole} role.";
                return false;
            }

            var requiredGroup = _store.Groups
                .FirstOrDefault(g => g.Name.Equals(_currentTicket.RequiredGroupName, StringComparison.OrdinalIgnoreCase));

            if (requiredGroup == null)
            {
                message = $"Required group {_currentTicket.RequiredGroupName} was not found.";
                return false;
            }

            if (!user.GroupIds.Contains(requiredGroup.Id))
            {
                message = $"{user.DisplayName} is not in {_currentTicket.RequiredGroupName}.";
                return false;
            }

            bool hasActiveAssignedDevice = _store.Devices.Any(d =>
                d.AssignedUserId == user.Id &&
                d.Status == Models.DeviceStatus.Active);

            if (!hasActiveAssignedDevice)
            {
                message = $"{user.DisplayName} does not have an active assigned device.";
                return false;
            }

            bool hasCreatedUserAudit = _store.AuditEntries.Any(a =>
                a.Action == "Created User" &&
                a.Target == user.DisplayName);

            if (!hasCreatedUserAudit)
            {
                message = $"No Created User audit entry found for {user.DisplayName}.";
                return false;
            }

            message = "New hire onboarding ticket completed successfully.";
            return true;
        }

        // Validates email troubleshooting actions such as clearing mailbox full, assigning license, disabling forwarding, or unblocking mailbox.
        private bool ValidateEmailTroubleshootingTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email.Equals(_currentTicket.TargetUserEmail, StringComparison.OrdinalIgnoreCase));

            if (user == null)
            {
                message = "Target user was not found.";
                return false;
            }

            switch (_currentTicket.RequiredEmailIssue)
            {
                case "MailboxFull":
                    if (user.MailboxFull)
                    {
                        message = $"{user.DisplayName}'s mailbox is still marked full.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Cleared Mailbox Full Warning", user.DisplayName))
                    {
                        message = $"No mailbox full warning clearance audit entry found for {user.DisplayName}.";
                        return false;
                    }

                    break;

                case "MissingMailLicense":
                    if (!user.HasMailLicense)
                    {
                        message = $"{user.DisplayName} still does not have a mail license.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Assigned Mail License", user.DisplayName))
                    {
                        message = $"No mail license assignment audit entry found for {user.DisplayName}.";
                        return false;
                    }

                    break;

                case "ForwardingEnabled":
                    if (user.ForwardingEnabled)
                    {
                        message = $"{user.DisplayName} still has mail forwarding enabled.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Disabled Mail Forwarding", user.DisplayName))
                    {
                        message = $"No disabled forwarding audit entry found for {user.DisplayName}.";
                        return false;
                    }

                    break;

                case "MailboxBlocked":
                    if (user.MailboxBlocked)
                    {
                        message = $"{user.DisplayName}'s mailbox is still blocked.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Unblocked Mailbox", user.DisplayName))
                    {
                        message = $"No mailbox unblock audit entry found for {user.DisplayName}.";
                        return false;
                    }

                    break;

                default:
                    message = "Unknown email troubleshooting issue type.";
                    return false;
            }

            message = "Email troubleshooting ticket completed successfully.";
            return true;
        }

        // Validates device-health remediation such as Windows Update, BitLocker, Defender, disk cleanup, or check-in refresh.
        private bool ValidateDeviceHealthTroubleshootingTicket(out string message)
        {
            var user = _store.Users
                .FirstOrDefault(u => u.Email.Equals(_currentTicket.TargetUserEmail, StringComparison.OrdinalIgnoreCase));

            if (user == null)
            {
                message = "Target user was not found.";
                return false;
            }

            var device = GetRequiredTicketDevice();

            if (device == null)
            {
                message = $"Required device {_currentTicket.RequiredDeviceName} was not found.";
                return false;
            }

            if (device.AssignedUserId != user.Id)
            {
                message = $"{device.DeviceName} is not assigned to {user.DisplayName}.";
                return false;
            }

            switch (_currentTicket.RequiredDeviceIssue)
            {
                case "WindowsUpdatePending":
                    if (device.WindowsUpdatePending)
                    {
                        message = $"{device.DeviceName} still has pending Windows updates.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Ran Windows Update", device.DeviceName))
                    {
                        message = $"No Windows Update audit entry found for {device.DeviceName}.";
                        return false;
                    }
                    break;

                case "BitLockerDisabled":
                    if (!device.BitLockerEnabled)
                    {
                        message = $"{device.DeviceName} still does not have BitLocker enabled.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Enabled BitLocker", device.DeviceName))
                    {
                        message = $"No BitLocker audit entry found for {device.DeviceName}.";
                        return false;
                    }
                    break;

                case "DefenderDisabled":
                    if (!device.DefenderEnabled)
                    {
                        message = $"{device.DeviceName} still has Defender disabled.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Enabled Defender", device.DeviceName))
                    {
                        message = $"No Defender audit entry found for {device.DeviceName}.";
                        return false;
                    }
                    break;

                case "LowDiskSpace":
                    if (device.DiskSpaceFreePercent < 15)
                    {
                        message = $"{device.DeviceName} still has low disk space.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Cleared Disk Space", device.DeviceName))
                    {
                        message = $"No disk cleanup audit entry found for {device.DeviceName}.";
                        return false;
                    }
                    break;

                case "CheckInStale":
                    if (device.DaysSinceLastCheckIn > 7)
                    {
                        message = $"{device.DeviceName} still has a stale check-in.";
                        return false;
                    }

                    if (!HasAuditEntrySinceTicketLoaded("Refreshed Device Check-In", device.DeviceName))
                    {
                        message = $"No check-in refresh audit entry found for {device.DeviceName}.";
                        return false;
                    }
                    break;

                default:
                    message = "Unknown device health issue type.";
                    return false;
            }

            message = "Device health troubleshooting ticket completed successfully.";
            return true;
        }

