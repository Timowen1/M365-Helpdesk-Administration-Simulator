        // Selects the first visible user row after a search or reload while avoiding hidden grid cells.
        private void SelectFirstUserRowIfAvailable()
        {
            if (usersGridView.Rows.Count == 0)
            {
                usersGridView.ClearSelection();
                DisplaySelectedUser();
                return;
            }

            usersGridView.ClearSelection();

            var firstVisibleCell = usersGridView.Rows[0]
                .Cells
                .Cast<DataGridViewCell>()
                .FirstOrDefault(cell => cell.Visible);

            if (firstVisibleCell == null)
            {
                DisplaySelectedUser();
                return;
            }

            usersGridView.CurrentCell = firstVisibleCell;
            usersGridView.Rows[0].Selected = true;

            DisplaySelectedUser();
            UpdateTicketProgress();
        }

