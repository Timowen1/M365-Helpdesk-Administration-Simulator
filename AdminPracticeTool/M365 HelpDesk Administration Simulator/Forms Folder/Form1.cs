        private void usersGridView_SelectionChanged(object sender, EventArgs e)
        {
            DisplaySelectedUser();

            if (!_isLoadingTicket)
            {
                UpdateTicketProgress();
            }
        }

        // Applies common read-only display settings and hides internal data columns in the user grid.
        private void FormatUsersGrid()
        {
            if (usersGridView.Columns["Id"] != null)
                usersGridView.Columns["Id"].Visible = false;

            if (usersGridView.Columns["GroupIds"] != null)
                usersGridView.Columns["GroupIds"].Visible = false;

            if (usersGridView.Columns["DeviceIds"] != null)
                usersGridView.Columns["DeviceIds"].Visible = false;

            if (usersGridView.Columns["CreatedAt"] != null)
                usersGridView.Columns["CreatedAt"].Visible = false;

            usersGridView.AutoSizeColumnsMode = DataGridViewAutoSizeColumnsMode.Fill;
            usersGridView.SelectionMode = DataGridViewSelectionMode.FullRowSelect;
            usersGridView.MultiSelect = false;
            usersGridView.ReadOnly = true;
        }

        // Checks whether a matching audit entry was created after the current ticket loaded, preventing old actions from completing new tickets.
        private bool HasAuditEntrySinceTicketLoaded(string action, string target = null, string notesContains = null)
        {
            return _store.AuditEntries.Any(a =>
                a.Timestamp >= _currentTicketLoadedAt &&
                a.Action == action &&
                (target == null || a.Target == target) &&
                (notesContains == null || a.Notes.Contains(notesContains)));
        }


