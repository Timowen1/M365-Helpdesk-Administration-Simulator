        private Services.TicketQueueService _ticketQueueService;

        // Prevents the "ticket ready" popup from showing repeatedly for the same ticket.
        private bool _currentTicketReadyToComplete;

        // Used so validation/checklists only count actions performed after this ticket loaded.
        private DateTime _currentTicketLoadedAt;

        // Prevents selection-change events from updating tickets while a ticket is being loaded.
        private bool _isLoadingTicket;

        // Initializes fake data, loads ticket scenarios, populates the dashboard, and starts the first ticket.
        public Form1()
        {
            InitializeComponent();

            _store = Services.SeedDataService.CreateSeedData();
            _ticketQueueService = new Services.TicketQueueService();

            var scenarios = Services.TicketScenarioService.LoadScenariosFromJson();
            _ticketQueueService.LoadQueue(scenarios);

            LoadUsersGrid();
            LoadAuditGrid();
            LoadGroupsComboBox();
            LoadDevicesComboBox();
            DisplaySelectedUser();
            LoadNextTicketFromQueue();
        }

        // Reserved WinForms load event. Currently unused because startup initialization happens in the constructor.
        private void Form1_Load(object sender, EventArgs e)
        {

        }

        // Refreshes the user grid from the current fake data store and reapplies grid formatting.
        private void LoadUsersGrid()
        {
            usersGridView.DataSource = null;
            usersGridView.DataSource = _store.Users;

            FormatUsersGrid();
        }

        // Refreshes the audit log grid, newest entries first, and hides internal identifier columns.
        private void LoadAuditGrid()
        {
            auditGridView.AutoGenerateColumns = true;
            auditGridView.DataSource = null;
            auditGridView.DataSource = _store.AuditEntries
                .OrderByDescending(a => a.Timestamp)
                .ToList();

            if (auditGridView.Columns["Id"] != null)
                auditGridView.Columns["Id"].Visible = false;

            auditGridView.AutoSizeColumnsMode = DataGridViewAutoSizeColumnsMode.Fill;
            auditGridView.SelectionMode = DataGridViewSelectionMode.FullRowSelect;
            auditGridView.MultiSelect = false;
            auditGridView.ReadOnly = true;
        }

        // Dequeues and displays the next ticket scenario. If the queue is empty, clears the ticket panel.
        private void LoadNextTicketFromQueue()
        {
            var nextTicket = _ticketQueueService.GetNextTicket();

            if (nextTicket == null)
            {
                ticketTitleLabel.Text = "No tickets remaining";
                ticketDescriptionTextBox.Text = "The ticket queue is empty.";
                expectedActionsCheckedListBox.Items.Clear();

                _currentTicket = null;
                _currentTicketReadyToComplete = false;

                MessageBox.Show("All tickets are complete. Queue empty.");
                return;
            }

            _currentTicketReadyToComplete = false;
            _currentTicketLoadedAt = DateTime.Now;

            _isLoadingTicket = true;
            DisplayTicket(nextTicket);
            _isLoadingTicket = false;
        }

